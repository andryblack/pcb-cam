//! CAM operations in the project timeline.

use crate::LayerId;

/// Stable identifier of an operation inside a [`Project`](crate::Project).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct OperationId(u64);

impl OperationId {
    /// Construct an identifier from its numeric value.
    pub const fn new(value: u64) -> Self {
        Self(value)
    }

    /// Numeric value of the identifier.
    pub const fn value(self) -> u64 {
        self.0
    }
}

/// Parameters of a drilling operation.
#[derive(Debug, Clone, PartialEq)]
pub struct DrillOperation {
    /// Excellon layer that supplies the holes.
    pub layer: LayerId,
    /// Cut depth below the board surface, in millimetres.
    pub depth_mm: f64,
    /// Safe Z height, in millimetres.
    pub retract_mm: f64,
    /// XY feed rate for slots.
    pub feed_mm_min: f64,
    /// Z plunge rate.
    pub plunge_mm_min: f64,
    /// Dwell at the bottom of each hole, in seconds.
    pub dwell_s: f64,
    /// Spindle speed.
    pub spindle_rpm: u32,
}

impl DrillOperation {
    /// Sensible defaults for a new drilling operation.
    pub const fn new(layer: LayerId) -> Self {
        Self {
            layer,
            depth_mm: 1.8,
            retract_mm: 3.0,
            feed_mm_min: 300.0,
            plunge_mm_min: 120.0,
            dwell_s: 0.1,
            spindle_rpm: 10_000,
        }
    }

    /// Validate the operation before generating G-code.
    pub fn validate(&self) -> Result<(), String> {
        if !self.depth_mm.is_finite() || self.depth_mm <= 0.0 {
            return Err("drill depth must be greater than zero".into());
        }
        if !self.retract_mm.is_finite() || self.retract_mm <= 0.0 {
            return Err("retract height must be greater than zero".into());
        }
        if !self.feed_mm_min.is_finite() || self.feed_mm_min <= 0.0 {
            return Err("feed rate must be greater than zero".into());
        }
        if !self.plunge_mm_min.is_finite() || self.plunge_mm_min <= 0.0 {
            return Err("plunge rate must be greater than zero".into());
        }
        if !self.dwell_s.is_finite() || self.dwell_s < 0.0 {
            return Err("dwell must not be negative".into());
        }
        if self.spindle_rpm == 0 {
            return Err("spindle speed must be greater than zero".into());
        }
        Ok(())
    }
}

/// The kind-specific parameters of an operation.
#[derive(Debug, Clone, PartialEq)]
pub enum OperationKind {
    /// Drill all holes and rout all slots in an Excellon layer.
    Drill(DrillOperation),
}

/// A single CAM operation in the project timeline.
#[derive(Debug, Clone, PartialEq)]
pub struct Operation {
    id: OperationId,
    name: String,
    enabled: bool,
    kind: OperationKind,
}

impl Operation {
    pub(crate) fn new(id: OperationId, name: String, kind: OperationKind) -> Self {
        Self {
            id,
            name,
            enabled: true,
            kind,
        }
    }

    /// Stable operation identifier.
    pub const fn id(&self) -> OperationId {
        self.id
    }

    /// Display name.
    pub fn name(&self) -> &str {
        &self.name
    }

    /// Rename the operation. Empty names are ignored.
    pub fn set_name(&mut self, name: impl Into<String>) {
        let name = name.into();
        let name = name.trim();
        if !name.is_empty() {
            self.name = name.to_owned();
        }
    }

    /// Whether the operation is generated by the post-processor.
    pub const fn enabled(&self) -> bool {
        self.enabled
    }

    /// Enable or disable the operation.
    pub fn set_enabled(&mut self, enabled: bool) {
        self.enabled = enabled;
    }

    /// Operation parameters.
    pub const fn kind(&self) -> &OperationKind {
        &self.kind
    }

    /// Mutable operation parameters.
    pub fn kind_mut(&mut self) -> &mut OperationKind {
        &mut self.kind
    }

    /// Short kind label.
    pub const fn kind_label(&self) -> &'static str {
        match self.kind {
            OperationKind::Drill(_) => "Drill",
        }
    }

    /// Source layer this operation consumes.
    pub const fn source_layer(&self) -> LayerId {
        match &self.kind {
            OperationKind::Drill(drill) => drill.layer,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn drill_defaults_validate() {
        let drill = DrillOperation::new(LayerId::new(1));
        assert!(drill.validate().is_ok());
    }

    #[test]
    fn drill_validation_rejects_bad_values() {
        let mut drill = DrillOperation::new(LayerId::new(1));
        drill.depth_mm = 0.0;
        assert!(drill.validate().is_err());
        drill.depth_mm = 1.0;
        drill.spindle_rpm = 0;
        assert!(drill.validate().is_err());
    }
}
